// Font classes
export const SAFE_FONT_CLASSES: Record<string, string> = {
  'font-sans': 'font-sans',
  'font-serif': 'font-serif',
  'font-mono': 'font-mono',
};

/**
 * Get safe background color class
 * @param color - Color name (e.g., "amber-700")
 * @returns Tailwind class or fallback
 */
export function getSafeBgColor(color: string): string {
  return SAFE_BG_COLORS[color] || SAFE_BG_COLORS['gray-100'];
}

/**
 * Get safe text color class
 * @param color - Color name (e.g., "amber-700")
 * @returns Tailwind class or fallback
 */
export function getSafeTextColor(color: string): string {
  return SAFE_TEXT_COLORS[color] || SAFE_TEXT_COLORS['gray-800'];
}

/**
 * Get safe border color class
 * @param color - Color name (e.g., "amber-200")
 * @returns Tailwind class or fallback
 */
export function getSafeBorderColor(color: string): string {
  return SAFE_BORDER_COLORS[color] || SAFE_BORDER_COLORS['gray-300'];
}

/**
 * Get safe gradient class
 * @param gradient - Gradient name (e.g., "amber-orange-red")
 * @returns Tailwind class or fallback
 */
export function getSafeGradient(gradient: string): string {
  return SAFE_GRADIENTS[gradient] || SAFE_GRADIENTS['gray-gradient'];
}

/**
 * Get safe font class
 * @param font - Font name (e.g., "font-serif")
 * @returns Tailwind class or fallback
 */
export function getSafeFont(font: string): string {
  return SAFE_FONT_CLASSES[font] || SAFE_FONT_CLASSES['font-sans'];
}
